"""Gothic Terminal: glyph bitmaps.

Monospace cell: 8 px wide (7 drawn + 1 gap), 16 px tall.
Style rules: vertical strokes 2 px, horizontals and diagonals 1 px
(blackletter thick/thin), broken corners on round letters, hooked caps.

Each entry: char -> (bottom_y, rows). Rows go top to bottom, '#' = pixel.
bottom_y is the y of the last row; baseline is y=0, x-height top y=6,
cap/ascender top y=9, descenders go down to y=-3.
"""

G = {}

def g(chars, bottom, art):
    rows = [r for r in art.strip('\n').split('\n')]
    for r in rows:
        assert len(r) == 7, (chars, r)
    G[chars] = (bottom, rows)

def mirror(src, dst):
    b, rows = G[src]
    G[dst] = (b, [r[::-1] for r in rows])

